// ひらがなをカタカナにする
function hiraganaToKatakana(s: string): string {
  return s.replace(/[ぁ-ゖ]/g, (c) => String.fromCharCode(c.charCodeAt(0) + 0x60));
}

// 全角カナを半角カナにする
function toHalfKana(s: string): string {
  return [...s].map((c) => FULL_TO_HALF[c] ?? c).join("");
}

// 検索語の表記違い（入力のまま・全角カナと半角英数・半角カナ）を重複なく返す
export function kanaVariants(input: string): string[] {
  const raw = input.trim();
  if (!raw) return [];
  const normalized = hiraganaToKatakana(raw.normalize("NFKC")); // 半角カナ→全角カナ、全角英数→半角英数
  return [...new Set([raw, normalized, toHalfKana(normalized)])];
}
